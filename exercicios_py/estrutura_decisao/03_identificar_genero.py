genero_inserido = input("Qual o seu genêro? (M ou F): ")

if genero_inserido == "M":
    print("Você é homem!")
elif genero_inserido == "F":
    print("Você é mulher!")
else:
    print("Genêro inválido!")

# O programa identifica o genêro do usuário de acordo se ele escolher M para Homem, F para Mulher e se nenhuma dessas duas opções foram digitadas fosse imprimido uma resposta de erro.